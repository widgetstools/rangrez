/// Parse an ISO-8601 date / datetime to epoch milliseconds (UTC). Hand-rolled:
/// the 1.78 toolchain pin rules out chrono's newer releases, and the accepted
/// grammar here is deliberately narrow — `YYYY-MM-DD`, optionally
/// `T?HH:MM[:SS[.fff]]` and a trailing `Z` or `±HH:MM` offset. A plain epoch
/// number (the shape a typed date column may carry) also parses.
pub fn parse_iso_ms(s: &str) -> Option<i64> {
    let t = s.trim();
    if t.is_empty() { return None; }
    // Already-numeric epoch (typed date columns store display string + epoch;
    // an expression built on the epoch shadow sends the number as a string).
    if t.chars().all(|c| c.is_ascii_digit() || c == '-' || c == '+') && t.len() >= 11 {
        if let Ok(ms) = t.parse::<i64>() { return Some(ms); }
    }
    let b = t.as_bytes();
    if b.len() < 10 || b[4] != b'-' || b[7] != b'-' { return None; }
    let year: i64 = t.get(0..4)?.parse().ok()?;
    let month: u32 = t.get(5..7)?.parse().ok()?;
    let day: u32 = t.get(8..10)?.parse().ok()?;
    if !(1..=12).contains(&month) || !(1..=31).contains(&day) { return None; }
    let mut ms = days_from_civil(year, month, day) * 86_400_000;
    let mut rest = &t[10..];
    if let Some(stripped) = rest.strip_prefix('T').or_else(|| rest.strip_prefix(' ')) { rest = stripped; }
    // Offset suffix first, so the time slice below is clean.
    let mut offset_min: i64 = 0;
    if let Some(stripped) = rest.strip_suffix('Z') {
        rest = stripped;
    } else if rest.len() >= 6 {
        let tail = &rest[rest.len() - 6..];
        let tb = tail.as_bytes();
        if (tb[0] == b'+' || tb[0] == b'-') && tb[3] == b':' {
            if let (Ok(h), Ok(m)) = (tail[1..3].parse::<i64>(), tail[4..6].parse::<i64>()) {
                offset_min = h * 60 + m;
                if tb[0] == b'-' { offset_min = -offset_min; }
                rest = &rest[..rest.len() - 6];
            }
        }
    }
    if !rest.is_empty() {
        let hb = rest.as_bytes();
        if hb.len() < 5 || hb[2] != b':' { return None; }
        let hh: i64 = rest.get(0..2)?.parse().ok()?;
        let mm: i64 = rest.get(3..5)?.parse().ok()?;
        let mut ss: i64 = 0;
        let mut frac: i64 = 0;
        if hb.len() >= 8 && hb[5] == b':' {
            ss = rest.get(6..8)?.parse().ok()?;
            if hb.len() > 9 && hb[8] == b'.' {
                let digits = &rest[9..];
                let take = digits.len().min(3);
                let val: i64 = digits.get(0..take)?.parse().ok()?;
                frac = val * 10i64.pow(3 - take as u32);
            }
        }
        ms += (hh * 3600 + mm * 60 + ss) * 1000 + frac;
    }
    Some(ms - offset_min * 60_000)
}

/// Days since 1970-01-01 for a civil date (Howard Hinnant's algorithm).
fn days_from_civil(y: i64, m: u32, d: u32) -> i64 {
    let y = if m <= 2 { y - 1 } else { y };
    let era = if y >= 0 { y } else { y - 399 } / 400;
    let yoe = (y - era * 400) as i64;
    let mp = ((m + 9) % 12) as i64;
    let doy = (153 * mp + 2) / 5 + d as i64 - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146_097 + doe - 719_468
}

/// Civil (year, month, day) from epoch ms — UTC.
fn civil_from_ms(ms: i64) -> (i64, u32, u32) {
    let z = ms.div_euclid(86_400_000) + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    (if m <= 2 { y + 1 } else { y }, m, d)
}

/// Day of week for epoch ms — 0 = Sunday, matching `Date.getDay()`.
fn weekday(ms: i64) -> u32 {
    let days = ms.div_euclid(86_400_000);
    ((days + 4).rem_euclid(7)) as u32
}

// ---------------------------------------------------- client aggregate scalars

/// One aggregate scalar with the CLIENT's fold semantics (`functions.ts`), used
/// for expression `agg` nodes. These differ from the grid's group aggregates:
/// SUM/AVG coerce every value through `toNum` (null counts as 0 and is
/// included in AVG's divisor), while COUNT/DISTINCT_COUNT skip nulls.
pub fn client_aggregate(func: &str, values: &mut dyn Iterator<Item = Value>) -> Value {
    match func {
        "count" => Value::Float(values.filter(|v| !matches!(v, Value::Null)).count() as f64),
        "distinct_count" => {
            let mut seen = std::collections::HashSet::new();
            for v in values {
                if matches!(v, Value::Null) { continue; }
                // Type-tagged key: SameValueZero keeps 5 and "5" distinct.
                let key = match &v {
                    Value::Bool(b) => format!("b{b}"),
                    Value::Int(i) => format!("n{}", *i as f64),
                    Value::Float(f) => format!("n{f}"),
                    Value::Str(s) => format!("s{s}"),
                    Value::Null => unreachable!(),
                };
                seen.insert(key);
            }
            Value::Float(seen.len() as f64)
        }
        "sum" => Value::Float(values.map(|v| to_num(&v)).sum::<f64>()),
        "avg" => {
            let nums: Vec<f64> = values.map(|v| to_num(&v)).collect();
            if nums.is_empty() { Value::Float(0.0) }
            else { Value::Float(nums.iter().sum::<f64>() / nums.len() as f64) }
        }
        "min" | "max" => {
            let nums: Vec<f64> = values.map(|v| to_num(&v)).collect();
            if nums.is_empty() { return Value::Float(0.0); }
            if nums.iter().any(|n| n.is_nan()) { return Value::Float(f64::NAN); }
            let init = nums[0];
            Value::Float(nums.into_iter().fold(init, |a, n| if func == "min" { a.min(n) } else { a.max(n) }))
        }
        "median" => {
            let mut nums: Vec<f64> = values.map(|v| to_num(&v)).collect();
            if nums.is_empty() { return Value::Float(0.0); }
            nums.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));
            let mid = nums.len() / 2;
            Value::Float(if nums.len() % 2 == 0 { (nums[mid - 1] + nums[mid]) / 2.0 } else { nums[mid] })
        }
        "stdev" | "variance" => {
            let nums: Vec<f64> = values.map(|v| to_num(&v)).collect();
            if nums.len() <= 1 { return Value::Float(0.0); }
            let mean = nums.iter().sum::<f64>() / nums.len() as f64;
            let var = nums.iter().map(|n| (n - mean) * (n - mean)).sum::<f64>() / (nums.len() - 1) as f64;
            Value::Float(if func == "stdev" { var.sqrt() } else { var })
        }
        _ => Value::Null,
    }
}
